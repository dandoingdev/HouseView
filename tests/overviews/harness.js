// Per-overview browser harness: mounts each overview's fixtures through the REAL bundle (a carousel with the
// overview as a page card, a carousel with the overview as its screensaver, or the standalone element) and runs
// its test.js. The overview twin of tests/widgets/harness.js (docs/overview-api.md).
//
//   node tools/run-tests.mjs tests/overviews/index.html --target=dist      # all overviews, dist/houseview.js
//   .../tests/overviews/index.html?kind=weather                            # some overviews
//   .../tests/overviews/index.html?src=/dist/houseview.js                  # another bundle
//
// Inputs: tests/overviews/manifest.js (generated by tools/gen-widgets.mjs: [{type, load:  => import(test.js)}]),
// src/overviews/<type>/fixtures.js for the variants, and the bundle given by `?src=`.
//
// What the harness guarantees to a test.js:
//   * a recording mock hass per mount (tests/fixtures/mock-hass.js) WITH a websocket connection: a
//     `weather/subscribe_forecast` subscription is answered at once, in a microtask, from the variant's
//     `forecasts`; every subscription is recorded on `t.connection.subscriptions`;
//   * a fixed clock (2026-10-15 10:10 Europe/London) and intervals that only fire through advance, so the real
//     shared ticker and the idle manager run on fake time;
//   * every mounted element removed after each overview's test (so disconnectedCallback runs).
//
// h = {mount, check, variants, wait, settle, now, advance, overview}. See `mount` for the handle it returns.

import {createMockHass} from '../fixtures/mock-hass.js';
import {installDeterminism, settle, defineDoubles} from '../widgets/harness.js';

/** The fixtures' clock (2026-10-15 10:09 Europe/London); the fake clock starts a minute later. */
export const PREVIEW_NOW = '2026-10-15T10:09:00+01:00';
/**
 * The subscription grace period of core/subscriptions.js (2000 ms, a real one-shot timer, not the fake clock) plus a
 * margin: how long remove({settle: true}) waits for the unsubscribe of the last lease.
 */
const GRACE_MS = 2100;

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const fixturesUrl = (type, base = '../../src/overviews') =>
  new URL(`${base.replace(/\/$/, '')}/${type}/fixtures.js`, import.meta.url).href;
const tagOf = (type) => `houseview-${type.replaceAll('_', '-')}-overview-card`;

/**
 * A websocket connection double on top of the mock hass: subscribeMessage answers a forecast subscription from the
 * variant at once (in a microtask) and records it as {callback, msg, message, active}.
 */
function connectionFor(mock, variant) {
  const subscriptions = [];
  const raw = mock.hass.connection;
  raw.subscribeMessage = (callback, msg) => {
    const record = {callback, msg, message: msg, active: true};
    subscriptions.push(record);
    const forecast = variant.forecasts?.[msg.forecast_type];
    queueMicrotask(() => {
      if (record.active && forecast !== undefined) callback({type: msg.forecast_type, forecast});
    });
    return Promise.resolve(() => {
      record.active = false;
    });
  };
  return {raw, subscriptions};
}

/**
 * Build the handle given to an overview's test.js.
 * @param {{type: string, env: ReturnType<typeof installDeterminism>, stage: Element, check: Function, variants: Object}} opts
 */
export function createHandle({type, env, stage, check, variants}) {
  const mounted = [];
  const tag = tagOf(type);
  const lights = {
    'light.a': {state: 'on', attributes: {friendly_name: 'Light A', supported_features: 0}},
    'light.b': {state: 'off', attributes: {friendly_name: 'Light B', supported_features: 0}}
  };
  const lightCards = [
    {type: 'custom:houseview-light-card', entity: 'light.a'},
    {type: 'custom:houseview-light-card', entity: 'light.b'}
  ];

  /**
   * Mount a fixture variant.
   * @param {{options: Object, states: Object, forecasts?: Object, config?: Object, hass?: Object}} variant
   * @param {Object} [opts]
   * @param {'card'|'screensaver'|'carousel'} [opts.mode]  'card' (default): a carousel with the overview alone on a
   *   page, so it fills it. 'screensaver': a carousel with two light widgets and the overview as its screensaver with
   *   `preview: true` (visible at once). 'carousel': the same carousel with NO screensaver unless `screensaver` is
   *   given (the zero-impact test).
   * @param {'standalone'} [opts.as]  the houseview-<type>-overview-card element instead of a carousel
   * @param {boolean} [opts.freeze]  default true: config.preview_time = the fixtures' 10:09. false: ctx.now follows the fake clock
   * @param {number} [opts.idle]  screensaver mode: idle_timeout seconds and NO preview, so the test drives activation with advance
   * @param {boolean} [opts.event]  screensaver mode, for an `activation: 'event'` overview: NO preview and NO idle_timeout, so the
   *   overview's autoShow decides: drive it with `setState` (hass updates) and `advance` (the shared tick)
   * @param {boolean} [opts.bare]  screensaver and carousel modes: NO default light widgets, the carousel holds exactly `opts.cards`
   *   (an overview that is built from the dashboard's own widgets, the home overview, is tested this way)
   * @param {Object[]} [opts.cards]  screensaver and carousel modes: more cards after the two light widgets (a `custom:houseview-timer-card`
   *   or a media player card: the widgets that switch the automatic displays on, docs/overview-api.md)
   * @param {Object|Object[]} [opts.screensaver]  extra keys merged into the block (a list replaces it)
   * @param {Object} [opts.config]  extra card config keys
   * @param {Object} [opts.connection]  another handle's `connection`: the same Home Assistant session (dedupe tests)
   * @param {number} [opts.width] @param {number} [opts.height]  420 x 320 for a card, the viewport for a screensaver
   */
  async function mount(variant, opts = {}) {
    const mode = opts.mode || 'card';
    const mock = createMockHass({
      ...(variant.hass || {}),
      connection: true,
      states: variant.states
    });
    // Another handle's connection (or its mock) means the same Home Assistant session: one subscription per spec.
    const shared = opts.connection ?? opts.mock?.wrapper;
    const connection = shared ?? connectionFor(mock, variant);
    if (shared) mock.hass.connection = shared.raw;
    mock.wrapper = connection;
    for (const [id, state] of Object.entries(lights)) {
      if (mode !== 'card' && !opts.bare && !mock.hass.states[id])
        mock.hass.states[id] = structuredClone(state);
    }

    const full = mode !== 'card' && !opts.as;
    const holder = document.createElement('section');
    holder.dataset.overviewType = type;
    holder.style.cssText = `width:${opts.width ?? (full ? window.innerWidth : 420)}px;height:${opts.height ?? (full ? window.innerHeight : 320)}px;position:relative;overflow:hidden`;
    stage.append(holder);

    const config = {...(variant.config || {}), ...(opts.config || {})};
    if (opts.freeze === false)
      delete config.preview_time; // ctx.now follows the fake clock
    else config.preview_time ??= PREVIEW_NOW;
    const block = {type, ...variant.options};
    let el;
    let card;
    if (opts.as === 'standalone') {
      el = document.createElement(tag);
      holder.append(el);
      el.setConfig({type: `custom:${tag}`, ...variant.options, ...opts.config});
      card = el._inner || el.shadowRoot?.querySelector('houseview-card');
    } else {
      el = document.createElement('houseview-card');
      holder.append(el);
      if (mode === 'card') {
        el.setConfig({
          ...config,
          cards: [{type: `custom:${tag}`, ...variant.options}]
        });
      } else {
        const screensaver =
          mode === 'carousel'
            ? opts.screensaver
            : Array.isArray(opts.screensaver)
              ? opts.screensaver
              : {
                  ...block,
                  ...(opts.event ? {} : opts.idle ? {idle_timeout: opts.idle} : {preview: true}),
                  ...opts.screensaver
                };
        el.setConfig({
          ...config,
          cards: [...(opts.bare ? [] : lightCards), ...(opts.cards ?? [])],
          ...(screensaver === undefined ? {} : {screensaver})
        });
      }
      card = el;
    }
    const infos = [];
    el.addEventListener('hass-more-info', (e) => infos.push(e.detail?.entityId));
    el.hass = mock.hass;
    await settle();

    const root = () => card?.shadowRoot || el.shadowRoot;
    const layer = () => root()?.querySelector('.hv-screensaver') ?? null;
    const pointer = (target, type_) =>
      target.dispatchEvent(
        new PointerEvent(type_, {
          bubbles: true,
          composed: true,
          cancelable: true,
          pointerType: 'touch'
        })
      );
    const t = {
      el,
      card,
      mock,
      hass: mock.hass,
      infos,
      connection,
      clock: {
        now: env.now,
        /** Move the fake clock forward to a time (ISO string or ms). It cannot go back. */
        set(target) {
          const ms = typeof target === 'number' ? target : Date.parse(target);
          env.advance(Math.max(0, ms - env.now()));
        }
      },
      get root() {
        return root();
      },
      get calls() {
        return mock.calls;
      },
      /** The .hv-screensaver element, or null. */
      get layer() {
        return layer();
      },
      /** Its data-state: entering | on | leaving, or null. */
      get layerState() {
        return layer()?.dataset.state ?? null;
      },
      q: (selector) => root()?.querySelector(selector) ?? null,
      qa: (selector) => [...(root()?.querySelectorAll(selector) ?? [])],
      text: (selector) => root()?.querySelector(selector)?.textContent.trim() ?? null,
      /** Press the button carrying data-action (and, optionally, data-entity). Resets t.calls first. */
      async click(action, entity) {
        const selector = `button[data-action="${action}"]${entity ? `[data-entity="${entity}"]` : ''}`;
        const button = root()?.querySelector(selector);
        if (!button) throw new Error(`no ${selector} in the rendered overview`);
        mock.calls.length = 0;
        button.click();
        await settle();
        return button;
      },
      async hold(selector) {
        const target = root()?.querySelector(selector);
        if (!target) throw new Error(`no ${selector} to hold`);
        mock.calls.length = 0;
        target.dispatchEvent(
          new PointerEvent('pointerdown', {bubbles: true, button: 0, pointerId: 1, isPrimary: true})
        );
        await new Promise((resolve) => setTimeout(resolve, 550));
        target.dispatchEvent(
          new PointerEvent('pointerup', {bubbles: true, button: 0, pointerId: 1, isPrimary: true})
        );
        card._suppressClickUntil = 0;
        await settle();
      },
      /** A tap on the screensaver: pointerdown, pointerup, click at the dismiss button. */
      async tap() {
        const button = layer()?.querySelector('.ov-dismiss');
        if (!button) throw new Error('no screensaver layer to tap');
        for (const kind of ['pointerdown', 'pointerup']) pointer(button, kind);
        button.dispatchEvent(
          new MouseEvent('click', {bubbles: true, composed: true, cancelable: true})
        );
        await settle(10);
      },
      /** Escape on the screensaver. */
      async wake() {
        const button = layer()?.querySelector('.ov-dismiss');
        if (!button) throw new Error('no screensaver layer to wake');
        button.dispatchEvent(
          new KeyboardEvent('keydown', {
            key: 'Escape',
            bubbles: true,
            composed: true,
            cancelable: true
          })
        );
        await settle(10);
      },
      /** Deliver {type, forecast} to every open subscription of that forecast_type ('daily' | 'hourly'). */
      pushForecast(forecastType, list) {
        for (const s of connection.subscriptions) {
          if (s.active && s.msg.forecast_type === forecastType) {
            s.callback({type: forecastType, forecast: list});
          }
        }
      },
      /** Merge into an entity in place and hand hass back to the card (the way Home Assistant pushes updates). */
      async setState(id, patch) {
        mock.setState(id, patch);
        el.hass = mock.hass;
        await settle();
      },
      /** Move the fake clock forward `seconds` (default 1), firing the shared ticker once per second. */
      advance(seconds = 1) {
        env.advance(seconds * 1000);
      },
      async settle(ms) {
        await settle(ms);
      },
      /** Remove the element. `{settle: true}` also waits out the subscription grace period. */
      async remove({settle: wait = false} = {}) {
        el.remove();
        holder.remove();
        if (wait) {
          await delay(GRACE_MS);
          await settle();
        }
      }
    };
    mounted.push(t);
    return t;
  }

  return {
    type,
    mount,
    check,
    variants,
    wait: delay,
    settle,
    now: env.now,
    advance: env.advance,
    intervalCount: env.intervalCount,
    cleanup() {
      for (const t of mounted.splice(0)) {
        try {
          t.el.remove();
          t.el.parentElement?.remove();
        } catch {
          /* already gone */
        }
      }
    }
  };
}

let determinism;
const installDeterminismOnce = () => (determinism ||= installDeterminism());

/**
 * Run every overview in the manifest, then the zero-impact test (which belongs to no overview).
 * @param {{params: URLSearchParams, results: Element, summary: Element, stage: Element}} opts
 */
export async function runSuite({params, results, summary, stage}) {
  const src = params.get('src') || '/dist/houseview.js';
  const env = installDeterminismOnce();
  defineDoubles();
  let passed = 0;
  let failed = 0;
  const errors = [];
  const record = (message) => {
    if (!/ResizeObserver loop/.test(message)) errors.push(message);
  };
  window.addEventListener('error', (e) => {
    record(e.message);
    if (/ResizeObserver loop/.test(e.message)) e.stopImmediatePropagation();
  });
  window.addEventListener('unhandledrejection', (e) =>
    record(String(e.reason?.message || e.reason))
  );
  const add = (ok, text) => {
    const li = document.createElement('li');
    li.textContent = `${ok ? 'PASS' : 'FAIL'} — ${text}`;
    results.append(li);
    ok ? passed++ : failed++;
  };
  const finish = (text) => {
    summary.textContent = `${passed} passed; ${failed} failed.${text ? ` ${text}` : ''}`;
    return {passed, failed};
  };

  let manifest;
  try {
    manifest = (await import(/* @vite-ignore */ params.get('manifest') || './manifest.js')).default;
  } catch (e) {
    add(false, `tests/overviews/manifest.js could not be loaded (run npm run gen): ${e.message}`);
    return finish();
  }
  const only = (params.get('kind') || '').split(',').filter(Boolean);
  const entries = manifest.filter((m) => !only.length || only.includes(m.type));
  if (!entries.length) {
    return finish(
      manifest.length
        ? `No overview matches ?kind=${only.join(',')}.`
        : 'No overviews registered yet (the manifest is empty).'
    );
  }

  try {
    await import(/* @vite-ignore */ src);
  } catch (e) {
    add(false, `bundle ${src} failed to load: ${e.message}`);
    return finish();
  }

  const run = async (type, label, variants, body) => {
    const check = (name, ok) => add(!!ok, `${label}: ${name}`);
    const before = passed + failed;
    const handle = createHandle({type, env, stage, check, variants});
    try {
      await body(handle, check);
    } catch (e) {
      check(`test threw: ${e.message}`, false);
      console.error(e);
    } finally {
      handle.cleanup();
    }
    if (passed + failed === before) add(false, `${label}: produced no checks`);
  };

  for (const entry of entries) {
    let variants;
    try {
      variants = (await import(fixturesUrl(entry.type, params.get('overviews') || undefined)))
        .variants;
      if (!variants || !Object.keys(variants).length)
        throw new Error('fixtures.js exports no variants');
    } catch (e) {
      add(false, `${entry.type}: fixtures.js could not be loaded: ${e.message}`);
      continue;
    }
    await run(entry.type, entry.type, variants, async (handle, check) => {
      // automatic per-variant checks: it mounts and renders in both modes, and nothing calls a service
      for (const [name, variant] of Object.entries(variants)) {
        errors.length = 0;
        try {
          const card = await handle.mount(variant);
          const screensaver = await handle.mount(variant, {mode: 'screensaver'});
          // `display: tile` cards render the compact face instead of the scene (the screensaver layer still has it)
          const tile = variant.options?.display === 'tile';
          const rendered = tile ? !!card.q('.ov-tile-face') : !!card.q('.ov-scene');
          const layered = !!screensaver.layer?.querySelector('.ov-scene');
          const quiet = card.calls.length === 0 && screensaver.calls.length === 0;
          await card.remove();
          await screensaver.remove();
          check(
            `variant "${name}" renders its scene in card and screensaver mode`,
            rendered && layered
          );
          check(
            `variant "${name}" mounts without a console error or a service call`,
            quiet && !errors.length
          );
          if (errors.length) console.error(`${entry.type}/${name}: ${errors.join(' | ')}`);
        } catch (e) {
          check(`variant "${name}" mounts without throwing (${e.message})`, false);
        }
      }
      // the overview's own test
      const test = (await entry.load()).default;
      if (typeof test !== 'function')
        throw new Error('test.js must default-export an async function');
      const own = passed + failed;
      await test(handle);
      if (passed + failed === own) check('test.js made no check() calls', false);
    });
  }

  // The screensaver must cost nothing when it is not configured (belongs to no overview). It runs once for the first
  // overview that starts by idle time and once for the first event overview (activation: 'event'), each with its own flow.
  try {
    const kinds = new Map();
    for (const entry of entries) {
      const variants = (await import(fixturesUrl(entry.type, params.get('overviews') || undefined)))
        .variants;
      const probe = createHandle({type: entry.type, env, stage, check: () => {}, variants});
      try {
        const t = await probe.mount(variants.ok, {mode: 'screensaver', event: true});
        // A control panel is operated, not tapped away: the zero-impact flow dismisses with a tap.
        if (t.card._screensaver?.entries[0]?.overview?.controls) continue;
        const activation = t.card._screensaver?.entries[0]?.event ? 'event' : 'idle';
        if (!kinds.has(activation)) kinds.set(activation, {entry, variants});
      } finally {
        probe.cleanup();
      }
    }
    const zero = (await import('./zero-impact.test.js')).default;
    for (const [activation, {entry, variants}] of kinds) {
      await run(
        entry.type,
        activation === 'idle' ? 'zero impact' : 'zero impact (event overview)',
        variants,
        (handle) => zero({...handle, overview: entry.type, activation})
      );
    }
  } catch (e) {
    add(false, `zero impact: ${e.message}`);
  }

  // The automatic displays belong to the overviews they name (timer_display -> timer, music_screensaver -> cover_art).
  try {
    const {AUTOMATIC, default: automatic} = await import('./automatic-displays.test.js');
    for (const entry of entries.filter((e) => e.type in AUTOMATIC)) {
      const variants = (await import(fixturesUrl(entry.type, params.get('overviews') || undefined)))
        .variants;
      await run(entry.type, 'automatic displays', variants, (handle) =>
        automatic({...handle, overview: entry.type})
      );
    }
  } catch (e) {
    add(false, `automatic displays: ${e.message}`);
  }
  return finish();
}
