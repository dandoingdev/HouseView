// Generate the committed discovery files for module folders (docs/architecture.md).
//
//   src/widgets/index.js        one import + registerWidget per widget folder
//   tests/widgets/manifest.js   one lazy import per widget folder that has a test.js
//
// Usage: node tools/gen-widgets.mjs [--check] [--root=<dir>] [--quiet]
//   --check   write nothing; exit 1 and name the stale files (CI runs this after `npm run gen`)
//   --root    treat <dir> as the repository root (used by scratch builds and tests)
//
// The generator tolerates an empty, missing or half-written widgets tree: a folder without an index.js
// is skipped, a missing directory yields an empty (but valid) index.
//
// ADDING A MODULE FAMILY (screensavers, overviews): append one entry to MODULE_ROOTS. Nothing else changes.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * @typedef {Object} ModuleRoot
 * @property {string} name       label for log output
 * @property {string} dir        folder holding one sub-folder per module, relative to the repo root
 * @property {string} index      generated registration file, relative to the repo root
 * @property {string} registry   import path of the registry from the index file
 * @property {string} register   registry function called once per module
 * @property {string} exportName named export listing the module definitions
 * @property {string} suffix     identifier suffix for the imported default exports
 * @property {string|null} manifest  generated list of per-module browser tests, or null
 * @property {boolean} [strings]  import each module's strings.js and pass it to the register function
 *                    (widgets; overviews register their own strings inside registerOverview)
 */

/** @type {ModuleRoot[]} */
export const MODULE_ROOTS = [
  {
    name: 'widgets',
    dir: 'src/widgets',
    index: 'src/widgets/index.js',
    registry: '../core/registry.js',
    register: 'registerWidget',
    exportName: 'widgets',
    suffix: 'Widget',
    manifest: 'tests/widgets/manifest.js',
    strings: true
  },
  {
    // Overviews and screensavers (docs/overview-api.md). `_shared/` is skipped like `widgets/_shared/`.
    name: 'overviews',
    dir: 'src/overviews',
    index: 'src/overviews/index.js',
    registry: '../core/overview-registry.js',
    register: 'registerOverview',
    exportName: 'overviews',
    suffix: 'Overview',
    manifest: 'tests/overviews/manifest.js'
  }
];

const HEADER = '// GENERATED by tools/gen-widgets.mjs. Do not edit by hand: run `npm run gen`.\n';

/** `media_player` -> `mediaPlayerWidget`. Suffix keeps reserved words (switch) valid identifiers. */
export function identifier(folder, suffix) {
  const camel = folder.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
  return `${camel}${suffix}`;
}

/** Module folders in a root: directories not starting with `_` or `.` that contain an index.js. */
export function listModules(repo, root) {
  const dir = path.join(repo, root.dir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, {withFileTypes: true})
    .filter((e) => e.isDirectory() && !/^[._]/.test(e.name))
    .map((e) => e.name)
    .filter((name) => fs.existsSync(path.join(dir, name, 'index.js')))
    .sort()
    .map((name) => ({
      name,
      ident: identifier(name, root.suffix),
      hasTest: fs.existsSync(path.join(dir, name, 'test.js')),
      hasStrings: fs.existsSync(path.join(dir, name, 'strings.js'))
    }));
}

function indexSource(root, modules) {
  const idents = new Map();
  for (const m of modules) {
    if (idents.has(m.ident))
      throw new Error(`gen: ${m.name} and ${idents.get(m.ident)} collide on ${m.ident}`);
    idents.set(m.ident, m.name);
  }
  if (!modules.length) return `${HEADER}\nexport const ${root.exportName} = [];\n`;
  const withStrings = root.strings ? modules.filter((m) => m.hasStrings) : [];
  const imports = modules.flatMap((m) => [
    `import ${m.ident} from './${m.name}/index.js';`,
    ...(withStrings.includes(m) ? [`import ${m.ident}Strings from './${m.name}/strings.js';`] : [])
  ]);
  const registration = withStrings.length
    ? [
        '',
        "// Each module's strings.js reaches the translator through the registry (docs/widget-api.md).",
        `const strings = [${modules.map((m) => (withStrings.includes(m) ? `${m.ident}Strings` : 'undefined')).join(', ')}];`,
        `${root.exportName}.forEach((definition, i) => ${root.register}(definition, strings[i]));`
      ]
    : [`for (const definition of ${root.exportName}) ${root.register}(definition);`];
  return [
    HEADER,
    `import {${root.register}} from '${root.registry}';`,
    ...imports,
    '',
    `export const ${root.exportName} = [${modules.map((m) => m.ident).join(', ')}];`,
    ...registration,
    ''
  ].join('\n');
}

function manifestSource(repo, root, modules) {
  const from = path.dirname(path.join(repo, root.manifest));
  const rows = modules
    .filter((m) => m.hasTest)
    .map((m) => {
      const rel = path
        .relative(from, path.join(repo, root.dir, m.name, 'test.js'))
        .split(path.sep)
        .join('/');
      return `  {type: '${m.name}', load: () => import('${rel.startsWith('.') ? rel : `./${rel}`}')}`;
    });
  return [
    HEADER,
    "// Each entry lazily imports a widget's browser test; the module default-exports `async (harness) => {}`.",
    `export const manifest = [${rows.length ? `\n${rows.join(',\n')}\n` : ''}];`,
    '',
    'export default manifest;',
    ''
  ].join('\n');
}

/** Format with the project's Prettier config so the committed files survive `prettier --write` unchanged. */
async function format(repo, file, source) {
  try {
    const prettier = await import('prettier');
    const options = (await prettier.resolveConfig(path.join(repo, file))) || {};
    return await prettier.format(source, {...options, parser: 'babel'});
  } catch {
    return source;
  }
}

/** @returns {Promise<{file:string, changed:boolean}[]>} */
export async function generate({repo = REPO, check = false, roots = MODULE_ROOTS} = {}) {
  const results = [];
  for (const root of roots) {
    const modules = listModules(repo, root);
    const outputs = [[root.index, indexSource(root, modules)]];
    if (root.manifest) outputs.push([root.manifest, manifestSource(repo, root, modules)]);
    for (const [file, raw] of outputs) {
      const next = await format(repo, file, raw);
      const abs = path.join(repo, file);
      const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
      const changed = current !== next;
      if (changed && !check) {
        fs.mkdirSync(path.dirname(abs), {recursive: true});
        fs.writeFileSync(abs, next);
      }
      results.push({file, changed, count: modules.length});
    }
  }
  return results;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const quiet = args.includes('--quiet');
  const rootArg = args.find((a) => a.startsWith('--root='));
  const repo = rootArg ? path.resolve(rootArg.slice('--root='.length)) : REPO;
  const results = await generate({repo, check});
  const stale = results.filter((r) => r.changed);
  if (check) {
    if (stale.length) {
      console.error(
        `gen: out of date (run \`npm run gen\`): ${stale.map((r) => r.file).join(', ')}`
      );
      process.exit(1);
    }
    if (!quiet) console.log('gen: generated files are up to date');
  } else if (!quiet) {
    for (const r of results)
      console.log(`gen: ${r.changed ? 'wrote' : 'unchanged'} ${r.file} (${r.count} modules)`);
  }
}
